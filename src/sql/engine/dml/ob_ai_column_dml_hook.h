#ifndef OCEANBASE_SQL_ENGINE_DML_OB_AI_COLUMN_DML_HOOK_H_
#define OCEANBASE_SQL_ENGINE_DML_OB_AI_COLUMN_DML_HOOK_H_

#include "lib/container/ob_array.h"
#include "lib/container/ob_se_array.h"
#include "lib/string/ob_string.h"
#include "share/ob_define.h"

namespace oceanbase
{
namespace sql
{

class ObTableModifyOp;
struct ObInsCtDef;
struct ObUpdCtDef;
struct ObUpdRtDef;
struct ObDelCtDef;

/**
 * The DML hook of the AI columns.
 *
 * The hook watches the INSERT/UPDATE/DELETE of the tables which own AI columns.
 * When a row is changed, the AI columns whose dependency columns were changed
 * lose their result and a task is created in oceanbase.__all_ai_column_task.
 *
 * The task rows and the invalidation of the results are executed by the very
 * same transaction as the business DML, so a rollback of the business DML
 * removes the tasks and restores the results as well.
 *
 * The hook does not touch the storage directly.  It only generates the
 * statements which have to be executed and appends them to the pending list of
 * the DML operator.  The statements are executed by flush() when the DML
 * operator has written all of its rows, because the invalidation of a result
 * has to be applied after the new row image of the business DML has been
 * written, otherwise the business DML would overwrite the invalidation with
 * the old value of the result column.
 */
class ObAiColumnDmlHook
{
public:
  /* the statements which are generated by the hook and which are executed when
   * the DML statement has written all of its rows */
  typedef common::ObSEArray<common::ObString, 16> StmtArray;

  /* the name of the task table, it is an inner table of the oceanbase database */
  static const char *get_task_table_name() { return "__all_ai_column_task"; }

  /* the state of a task which waits to be processed */
  static const int64_t TASK_STATE_PENDING = 0;
  /* the state of a task which is being retried */
  static const int64_t TASK_STATE_RETRYING = 3;

  /* collect the tasks of one inserted row */
  static int handle_insert(ObTableModifyOp &op, const ObInsCtDef &ins_ctdef);
  /* collect the tasks of one updated row */
  static int handle_update(ObTableModifyOp &op, const ObUpdCtDef &upd_ctdef, ObUpdRtDef &upd_rtdef);
  /* collect the clean up of the tasks of one deleted row */
  static int handle_delete(ObTableModifyOp &op, const ObDelCtDef &del_ctdef);
  /* execute the statements which were collected by the hook */
  static int flush(ObTableModifyOp &op);

  /* build the request id which is shared by all the AI columns of one row */
  static int gen_request_id(common::ObIAllocator &allocator, common::ObString &request_id);

private:
  static int gen_task_insert_stmt(ObTableModifyOp &op,
                                  const uint64_t table_id,
                                  const common::ObString &request_id,
                                  const common::ObString &rowkey_predicate,
                                  const common::ObSEArray<uint64_t, 16> &ai_column_ids,
                                  common::ObIAllocator &allocator,
                                  common::ObString &stmt);
  static int gen_task_delete_stmt(ObTableModifyOp &op,
                                  const uint64_t table_id,
                                  const common::ObString &rowkey_predicate,
                                  common::ObIAllocator &allocator,
                                  common::ObString &stmt);
  static int gen_result_invalidate_stmt(ObTableModifyOp &op,
                                        const common::ObString &db_name,
                                        const common::ObString &table_name,
                                        const common::ObSEArray<common::ObString, 16> &ai_column_names,
                                        const common::ObString &rowkey_predicate,
                                        common::ObIAllocator &allocator,
                                        common::ObString &stmt);
};

} // namespace sql
} // namespace oceanbase

#endif // OCEANBASE_SQL_ENGINE_DML_OB_AI_COLUMN_DML_HOOK_H_
