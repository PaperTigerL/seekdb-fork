namespace oceanbase
{
namespace sql
{

struct ObResolverParams;
class ObSQLSessionInfo;

/**
 * Resolver of the "file as database" table functions.
 *
 *   read_csv('/path/a.csv' [, header = true, sample_size = -1])
 *   read_json('/path/a.jsonl' [, format = 'newline_delimited'])
 *   read_parquet('/path/a.parquet')
 *   glob('/path/dir/<pattern>')
 *
 * The parser produces one T_FILE_TABLE_EXPRESSION node whose children are
 *   children_[0] the function name, a T_IDENT node
 *   children_[1] the argument list
 *   children_[2] the optional alias, may be NULL
 *
 * The argument list is built by the parser as
 *   <literal>                        a single positional argument (the path)
 *   T_LINK_NODE(literal, <named>)    the path plus named arguments
 *   T_LINK_NODE(<named>, ...)        named arguments only, the path is missing
 * where <named> is a T_FILE_TABLE_ARG node with the argument name and value.
 *
 * The resolved table item is of type TableItem::FILE_TABLE, its definition is
 * kept in TableItem::file_table_def_ and its columns are registered as column
 * items of the statement so that `select col ...` and `select *` can resolve
 * them.
 */
class ObFileTableResolver
{
public:
  /**
   * Everything the file table resolver needs from the enclosing resolver.
   * The table id is generated by the caller because ObStmtResolver keeps
   * generate_table_id() protected.
   */
  struct ResolveContext
  {
    ResolveContext()
        : allocator_(NULL),
          session_info_(NULL),
          params_(NULL),
          stmt_(NULL),
          table_id_(common::OB_INVALID_ID)
    {}
    common::ObIAllocator *allocator_;
    ObSQLSessionInfo *session_info_;
    ObResolverParams *params_;
    ObDMLStmt *stmt_;
    uint64_t table_id_;
  };

  /**
   * Resolve one file table function into a TableItem of type FILE_TABLE.
   * @param ctx       the resolve context
   * @param parse_tree the T_FILE_TABLE_EXPRESSION node
   * @param tbl_item  the resolved table item
   */
  static int resolve_file_table_item(const ResolveContext &ctx,
                                     const ParseNode &parse_tree,
                                     TableItem *&tbl_item);

  /**
   * Collect the columns of a FILE_TABLE table item. The order is the order of
   * ObFileTableDef::columns_, which is the order the columns were registered.
   */
  static int resolve_file_table_column_items(const TableItem &table_item,
                                             const ObDMLStmt *stmt,
                                             common::ObIArray<ColumnItem> &column_items);

  /**
   * Check whether a column of a FILE_TABLE table item exists.
   */
  static int check_file_table_column_exists(const TableItem &table_item,
                                            const ObDMLStmt *stmt,
                                            const common::ObString &col_name,
                                            bool &is_exist);

private:
  /// The feature is guarded by the session variable enable_file_sql.
  static int check_file_sql_enabled(ObSQLSessionInfo *session_info);
  /// Map the function name onto a file table format.
  static int dispatch_file_table_func(const common::ObString &func_name,
                                      ObFileTableFormat &format);
  /// Parse the argument list of the file table function.
  static int parse_file_table_args(const ParseNode &arg_node,
                                   ObFileTableFormat format,
                                   common::ObString &path,
                                   bool &has_header,
                                   int64_t &sample_size,
                                   common::ObString &format_value);
  /// Parse one named argument of the file table function.
  static int parse_file_table_named_arg(const ParseNode &arg_node,
                                        ObFileTableFormat format,
                                        bool &has_header,
                                        int64_t &sample_size,
                                        common::ObString &format_value);
  /// The file name suffix must match the format of the table function.
  static int check_file_table_suffix(ObFileTableFormat format, const common::ObString &path);
  /// The path must be inside the directory allowed by secure_file_priv.
  static int check_file_table_secure_path(ObSQLSessionInfo *session_info,
                                          const common::ObString &path);
  /// Infer the columns of the file by opening it with the file scan reader.
  static int infer_file_table_columns(common::ObIAllocator &allocator,
                                      ObFileTableFormat format,
                                      const common::ObString &path,
                                      bool has_header,
                                      int64_t sample_size,
                                      common::ObSEArray<ObFileTableColumnDef, 16,
                                                        common::ModulePageAllocator,
                                                        true> &columns);
  /// Register the columns of the file table as column items of the statement.
  static int gen_file_table_column_items(ObDMLStmt *stmt,
                                         ObRawExprFactory *expr_factory,
                                         TableItem &table_item);
};

} // namespace sql
} // namespace oceanbase

#endif // OB_FILE_TABLE_RESOLVER_H
